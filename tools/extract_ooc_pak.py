#!/usr/bin/env python3
"""Extract OutOfCommissionFix's embedded "finale2.sco" payload and regenerate
src/recovered_ooc_pak.inc (plus the golden decoded table/archive used by the
native self-test).

The reference decoder lives in tools/ooc_decode_ref.py. Run from the repo root:

    python ZolikaPatch_reconstruction/tools/extract_ooc_pak.py
"""
from __future__ import annotations

import hashlib
import importlib.util
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASI = ROOT / "game_refs" / "ZolikaPatch_original.asi.off"
OUT_DIR = ROOT / "ZolikaPatch_reconstruction" / "src"
IMAGE_BASE = 0x10000000
STREAM_VA = 0x100B6798
DEST_SIZE = 179536
BLOB_SIZE = 0x27FD4


def _load_decoder():
    spec = importlib.util.spec_from_file_location(
        "ooc_decode_ref", pathlib.Path(__file__).with_name("ooc_decode_ref.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.Decoder


Decoder = _load_decoder()


def va_to_off(va: int) -> tuple[bytes, int]:
    data = ASI.read_bytes()
    pe = int.from_bytes(data[0x3C:0x40], "little")
    coff = pe + 4
    nsec = int.from_bytes(data[coff + 2 : coff + 4], "little")
    opt_size = int.from_bytes(data[coff + 16 : coff + 18], "little")
    opt = coff + 20
    sec_off = opt + opt_size
    for i in range(nsec):
        b = sec_off + i * 40
        vsize = int.from_bytes(data[b + 8 : b + 12], "little")
        sva = int.from_bytes(data[b + 12 : b + 16], "little")
        rawptr = int.from_bytes(data[b + 20 : b + 24], "little")
        if sva <= va - IMAGE_BASE < sva + vsize:
            return data, rawptr + (va - IMAGE_BASE - sva)
    raise SystemExit("VA not mapped")


def adler_ooc(data: bytes) -> int:
    """The original's Adler-32 variant (1872-byte partition, 32-bit wrapping)."""
    a, b = 1, 0
    for i in range(0, len(data), 1872):
        for byte in data[i : i + 1872]:
            a = (a + byte) & 0xFFFFFFFF
            b = (b + a) & 0xFFFFFFFF
        a %= 0xFFF1
        b %= 0xFFF1
    return ((b << 16) | a) & 0xFFFFFFFF


def build_archive(table: bytes, name: str) -> tuple[bytes, int]:
    """The original's sub_1004ACE0 for a single registered entry."""
    size = len(table)
    pages = size >> 11
    remainder = size & 0x7FF
    if remainder:
        pages += 1
    total = (pages << 11) + 2048
    archive = bytearray(total)
    offset = 0

    def append(data: bytes) -> None:
        nonlocal offset
        archive[offset : offset + len(data)] = data
        offset += len(data)

    name_z = name.encode() + b"\0"
    header = struct.pack("<IIIIHH", 0x86723DFF, 3, 1, len(name_z) + 16, 0x10, 0xE9)
    append(header)
    record = bytearray(16)
    struct.pack_into("<I", record, 0, size)          # physical size
    struct.pack_into("<I", record, 4, 0)             # virtual size
    struct.pack_into("<I", record, 8, 1)             # index + 1
    struct.pack_into("<H", record, 12, pages)
    if remainder:
        pad = 2048 - remainder
        struct.pack_into("<H", record, 14, pad)
    append(bytes(record))
    append(name_z)
    offset = 2048
    append(table)
    if remainder:
        offset += 2048 - remainder                   # zero padding (buffer is zeroed)
    return bytes(archive), offset


def main() -> int:
    data, stream_off = va_to_off(STREAM_VA)
    blob = data[stream_off : stream_off + BLOB_SIZE]
    decoder = Decoder(blob, 0)
    pc = 0
    while True:
        nxt = decoder.decode(pc)
        if nxt == pc:
            break
        pc = nxt
    table = bytes(decoder.dest)
    assert len(table) == DEST_SIZE, len(table)
    trailer = struct.unpack_from(">I", blob, pc + 2)[0]
    assert adler_ooc(table) == trailer, "decoder/Adler mismatch"
    archive, final_offset = build_archive(table, "finale2.sco")
    fnv = 2166136261
    for byte in archive:
        fnv = ((fnv ^ byte) * 16777619) & 0xFFFFFFFF
    print(f"blob    {len(blob)} bytes sha256 {hashlib.sha256(blob).hexdigest()}")
    print(f"table   {len(table)} bytes adler {trailer:#010x} sha256 {hashlib.sha256(table).hexdigest()}")
    print(f"archive {len(archive)} bytes final-offset {final_offset} fnv1a {fnv:#010x} "
          f"sha256 {hashlib.sha256(archive).hexdigest()}")

    lines = ["// Generated by tools/extract_ooc_pak.py - do not edit.",
             '// The original ASI\'s compressed "finale2.sco" resource at 0x100B6798',
             f"// ({len(blob)} bytes; decodes to {DEST_SIZE} bytes, OOC Adler-32 {trailer:#010x},",
             f"// blob sha256 {hashlib.sha256(blob).hexdigest()}).",
             'extern "C" const unsigned char zpatch_ooc_blob[] = {']
    row: list[str] = []
    for byte in blob:
        row.append(f"0x{byte:02x},")
        if len(row) == 16:
            lines.append("    " + "".join(row))
            row = []
    if row:
        lines.append("    " + "".join(row))
    lines.append("};")
    (OUT_DIR / "recovered_ooc_pak.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_DIR / 'recovered_ooc_pak.inc'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
