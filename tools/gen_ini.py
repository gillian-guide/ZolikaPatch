#!/usr/bin/env python3
"""Generate the shipped ZolikaPatch.ini from the recovered catalogue.

The file is part of the INI contract: same name, same location next to the ASI,
`[Options]` with every key at the value the original ships, and the two
light-table sections the parser expects to exist. It is generated from
`source/options.inc` (itself generated from the behaviour inventory) so the
defaults in the file and the defaults the arms fall back to cannot drift apart.

    python tools/gen_ini.py [--check]
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "source" / "options.inc"
OUTPUT = ROOT / "ZolikaPatch.ini"

HEADER = """; ZolikaPatch.ini - generated by tools/gen_ini.py from source/options.inc.
; Values are the defaults the original ships; an absent key falls back to the
; arm's own default, which is the same number unless the arm says otherwise.
"""

SECTIONS = ("[PopupLightAngles]", "[HeadlightConeOffsets]")


def entries():
    for line in TABLE.read_text(encoding="utf-8").splitlines():
        if not line.startswith("ZP_OPTION("):
            continue
        body = line.split("(", 1)[1].rstrip(")")
        fields = [field.strip() for field in body.split(",")]
        key, shipped, _absent, _mask, _module, kind = fields
        yield key, shipped, kind


def render() -> str:
    lines = [HEADER, "[Options]"]
    for key, shipped, kind in entries():
        if kind == "string":
            # The one string-valued key: the loader only pre-reads it.
            lines.append(f"; {key} = common:/data/gta.dat")
            continue
        if shipped == "-1":
            # Absent from the shipped file; the arm's default is the contract.
            lines.append(f"; {key} = 0")
            continue
        lines.append(f"{key}={shipped}")
    lines.append("")
    for section in SECTIONS:
        lines.append(section)
        lines.append("; Car<N>Name / Car<N>Angle (or Offset), N = 1..512. An empty or")
        lines.append("; absent name skips the slot.")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("ZolikaPatch.ini is out of date; run tools/gen_ini.py")
        print("ZolikaPatch.ini up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.name} ({len(list(entries()))} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
