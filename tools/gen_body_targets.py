#!/usr/bin/env python3
"""Attribute branch targets to keys, from the reference sources.

A key's arm names the body it jumps to (`MakeJMP(match, &abi_xxx)`), and the body
table maps that symbol to the original ASI VA. That pairing is the attribution:
it comes from the reference's own code, not from decoding dump displacements,
which cannot distinguish bodies (its canonicalisation collapses them).

    python tools/gen_body_targets.py [--check]

Writes `tests/body_targets.tsv`: key, body symbol, original VA.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT.parent / "readable"
TABLE = REFERENCE / "source" / "hook_bodies.cpp"
SOURCES = REFERENCE / "source"
OUTPUT = ROOT / "tests" / "body_targets.tsv"

BODY_ROW = re.compile(r"^\s*([a-z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+)u,\s*//")
FUNCTION = re.compile(r"^\s*(?:void|std::?)+\s+Apply([A-Za-z0-9_]+)\s*\(")
JUMP = re.compile(r"Make(?:JMP|CALL)\([^,]+,\s*reinterpret_cast<void\s*\*>\(&(abi_[a-z0-9_]+)\)")


def bodies():
    found = {}
    for line in TABLE.read_text(encoding="utf-8", errors="replace").splitlines():
        match = BODY_ROW.match(line)
        if match:
            found[match.group(1)] = int(match.group(2), 16)
    return found


def arm_bodies():
    pairs = {}
    for path in sorted(SOURCES.glob("*.ixx")):
        key = None
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            function = FUNCTION.match(line)
            if function:
                key = function.group(1)
                continue
            if key is None:
                continue
            jump = JUMP.search(line)
            if jump:
                pairs.setdefault(key, set()).add(jump.group(1))
    return pairs


def main() -> int:
    table = bodies()
    pairs = arm_bodies()
    rows = []
    for key, symbols in sorted(pairs.items()):
        for symbol in sorted(symbols):
            va = table.get(symbol[4:] if symbol.startswith("abi_") else symbol)
            if va is None:
                continue
            rows.append((key, symbol, va))
    text = ["# Generated by tools/gen_body_targets.py from the reference sources.",
            "# key, body symbol, original ASI VA (the address the arm's jump names)."]
    text += [f"{key}\t{symbol}\t{va:08X}" for key, symbol, va in rows]
    rendered = "\n".join(text) + "\n"
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit("tests/body_targets.tsv is out of date; run tools/gen_body_targets.py")
        print(f"body_targets.tsv up to date ({len(rows)} row(s))")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.name}: {len(rows)} row(s), {len({row[0] for row in rows})} key(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
