#!/usr/bin/env python3
"""Generate src/recovered_skip_launcher.inc from evidence/skip_launcher_ops.json.

Usage:
    python ZolikaPatch_reconstruction/tools/gen_skip_launcher_inc.py [--check]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]

HEADER = """// Generated by tools/gen_skip_launcher_inc.py - do not edit.
// Source: evidence/skip_launcher_ops.json (recovered from the handlers at
// 0x10045ce0, 0x10004850 and 0x10004620; see the checkpoint evidence for the
// disassembly verification).
"""


def byte_array(name: str, values: list[int]) -> str:
    body = ", ".join(f"0x{value:02x}" for value in values)
    return f"static const std::uint8_t {name}[] = {{{body}}};\n"


def install_rows(installs: list[dict], table: str) -> str:
    rows = []
    for install in installs:
        rows.append(
            f'  {{"{install["signature"]}", {install["offset"]}, '
            f'0x{int(install["opcode"], 16):02x}, SkipHook::{install["hook"]}}},'
        )
    return f"static const SkipLauncherInstall {table}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    data = json.loads((ROOT / "evidence" / "skip_launcher_ops.json").read_text(encoding="utf-8"))
    lines = [HEADER]
    for entry in data["entries"]:
        index = entry["index"]
        for write_index, write in enumerate(entry.get("writes", [])):
            name = f"kSkipBytes_{index}_{write_index}"
            if "bytes" in write:
                values = [int(token, 16) for token in write["bytes"].split()]
                lines.append(byte_array(name, values))
    for index, collector in enumerate(data["collectors"]):
        values = [int(token, 16) for token in collector["bytes"].split()]
        lines.append(byte_array(f"kSkipCollectorBytes_{index}", values))
    lines.append("")

    for entry in data["entries"]:
        index = entry["index"]
        writes = entry.get("writes", [])
        if not writes:
            continue
        rows = []
        for write_index, write in enumerate(writes):
            offset = write["offset"]
            if "jump_to_entry" in write:
                rows.append(f"  {{{offset}, 4, nullptr, 0, {write['jump_to_entry']}u}},")
            elif "bytes" in write:
                values = [int(token, 16) for token in write["bytes"].split()]
                rows.append(
                    f"  {{{offset}, {len(values)}, kSkipBytes_{index}_{write_index}, 0, "
                    f"kNoJumpTarget}},"
                )
            else:
                rows.append(
                    f"  {{{offset}, {write['length']}, nullptr, {write['fill']}, kNoJumpTarget}},"
                )
        lines.append(
            f"static const SkipLauncherWrite kWrites_{index}[] = {{\n" + "\n".join(rows) + "\n};\n"
        )

    entry_rows = []
    for entry in data["entries"]:
        index = entry["index"]
        if entry.get("writes"):
            entry_rows.append(f'  {{"{entry["signature"]}", kWrites_{index}, '
                              f"sizeof(kWrites_{index}) / sizeof(kWrites_{index}[0])}},")
        else:
            entry_rows.append(f'  {{"{entry["signature"]}", nullptr, 0}},')
    lines.append(
        "static const SkipLauncherEntry kSkipLauncherEntries[] = {\n"
        + "\n".join(entry_rows)
        + "\n};\n"
    )

    collector_rows = []
    for index, collector in enumerate(data["collectors"]):
        target = ("SkipLauncherCollector::Target::first_two"
                  if collector["targets"] == "first-two"
                  else "SkipLauncherCollector::Target::last_two")
        values = collector["bytes"].split()
        collector_rows.append(
            f'  {{"{collector["pattern"]}", {target}, kSkipCollectorBytes_{index}, {len(values)}}},'
        )
    lines.append(
        "static const SkipLauncherCollector kSkipLauncherCollectors[] = {\n"
        + "\n".join(collector_rows)
        + "\n};\n"
    )

    dfa = data["dfa"]
    capture = dfa["captures"][0]
    lines.append(
        f'static const std::string_view kSkipLauncherDfaCapture = "{capture["signature"]}";\n'
        f'static const std::int32_t kSkipLauncherDfaCaptureOffset = {capture["offset"]};\n'
    )
    lines.append(install_rows(dfa["installs"], "kSkipLauncherDfaInstalls"))
    lines.append(install_rows(data["rom"]["installs"], "kSkipLauncherRomInstalls"))
    collected_rows = []
    for group in dfa.get("collected", []):
        targets = ", ".join(
            f'{{"{t["target"]}", {i}}}' for i, t in enumerate(group["targets"])
        )
        collected_rows.append(
            f'  {{"{group["collector"]}", kSkipCollectedTargets_{len(collected_rows)}, '
            f'{len(group["targets"])}}},'
        )
        lines.append(
            f"static const SkipLauncherCollectedTarget kSkipCollectedTargets_{len(collected_rows) - 1}[] = "
            "{\n" + targets + "\n};\n"
        )
    if collected_rows:
        lines.append(
            "static const SkipLauncherCollectedInstall kSkipLauncherDfaCollected[] = {\n"
            + "\n".join(collected_rows)
            + "\n};\n"
        )
    else:
        lines.append("static const SkipLauncherCollectedInstall* const kSkipLauncherDfaCollected = nullptr;\n")

    text = "\n".join(lines)
    destination = ROOT / "src" / "recovered_skip_launcher.inc"
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != text:
            print(f"stale generated table: {destination.name}", file=sys.stderr)
            return 1
        print(f"skip launcher table verified: {len(data['entries'])} entries, "
              f"{len(data['collectors'])} collectors, "
              f"{len(dfa['installs'])} dfa installs, "
              f"{len(data['rom']['installs'])} rom installs")
        return 0
    destination.write_text(text, encoding="utf-8")
    print(f"generated {destination.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
