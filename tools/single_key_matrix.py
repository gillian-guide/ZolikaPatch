#!/usr/bin/env python3
"""The true single-key matrix: every catalogue key, alone, on every image.

For each build image and each catalogue key this writes an INI with *every* key
explicitly `0` and that one key `1`, runs `zp_dump` as its own process, and records
the exit code. That is the difference from a hand-written one-line INI: a key that
is merely absent takes its default (most are `1`), so a one-line INI measures the
whole default set, not one key. The matrix is what attributes a fault to a key.

The one expected fault is `NoImpostorHeightCutoff` on 1.0.0.0: it reproduces the
original's access violation (`docs/parity.md`, "A preserved fault that the tools
cannot measure"), so that cell is recorded as evidence and does not fail the run.
Any other non-zero exit does.

    python tools/single_key_matrix.py                  # nine builds, all keys
    python tools/single_key_matrix.py --build 1 9      # selected builds
    python tools/single_key_matrix.py --key SpeedupBugFix
    python tools/single_key_matrix.py --tsv build/single-key.tsv

Exit status: 0 when every cell exits 0 except the documented one, 1 otherwise.
This is a measurement tool, not a ctest: 9 x 99 process launches.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dump_matrix import BUILDS, VERSIONS, exception_of, keys  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DUMP = ROOT / "build" / "win-x86" / "Release" / "zp_dump.exe"
IMAGES = ROOT.parent / "game_refs"

# The one fault the tree keeps on purpose, as (key, build).
EXPECTED_FAULTS = {("NoImpostorHeightCutoff", 1)}

SHORT = {
    "0xC0000005 ACCESS_VIOLATION": "AV",
    "0xC000001D ILLEGAL_INSTRUCTION": "UD",
    "0xC000008C ARRAY_BOUNDS_EXCEEDED": "AB",
    "0xC0000094 INTEGER_DIVIDE_BY_ZERO": "DZ",
    "0xC00000FD STACK_OVERFLOW": "SO",
    "0xC0000374 HEAP_CORRUPTION": "HC",
    "0xC0000409 STACK_BUFFER_OVERRUN": "SB",
}


def cell_text(code: int) -> str:
    """`ok`, a short exception tag, or the plain exit code."""
    if code == 0:
        return "ok"
    fault = exception_of(code)
    if fault:
        return SHORT.get(fault, "EX")
    return f"e{code}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", type=int, nargs="*", default=None,
                        help="builds to run (default: all nine images)")
    parser.add_argument("--key", action="append", default=None,
                        help="key to run (repeatable; default: the whole catalogue)")
    parser.add_argument("--dump", type=Path, default=DUMP, help="zp_dump.exe")
    parser.add_argument("--tsv", type=Path, default=None,
                        help="also write `key<TAB>build<TAB>exit<TAB>bytes` rows here")
    parser.add_argument("--quiet", action="store_true", help="summary only")
    options = parser.parse_args()

    if not options.dump.exists():
        raise SystemExit(f"{options.dump} is missing; build the release preset first")

    table = keys()
    if options.key:
        unknown = [key for key in options.key if key not in table]
        if unknown:
            raise SystemExit(f"not in the catalogue: {', '.join(unknown)}")
        table = [key for key in table if key in set(options.key)]

    builds = options.build or sorted(BUILDS)
    missing = [build for build in builds if not (IMAGES / f"{BUILDS[build]}.exe").exists()]
    if missing:
        raise SystemExit(f"no image in game_refs for build(s) {missing}")
    builds = sorted(builds)

    work = ROOT / "build" / "win-x86"
    ini = work / "single-key.ini"
    out = work / "single-key.txt"
    all_off = "[Options]\n" + "".join(f"{key}=0\n" for key in keys())

    results = {}   # (key, build) -> (exit code, bytes changed)
    unexpected = []
    total = 0
    for build in builds:
        image = IMAGES / f"{BUILDS[build]}.exe"
        for key in table:
            ini.write_text(all_off + f"{key}=1\n", encoding="utf-8")
            result = subprocess.run(
                [str(options.dump), "--exe", str(image), "--build", str(build),
                 str(out), str(ini)],
                capture_output=True, text=True, errors="replace")
            code = result.returncode & 0xFFFFFFFF
            wrote = 0
            match = re.search(r"(\d+) byte\(s\) changed", result.stdout)
            if match:
                wrote = int(match.group(1))
            results[(key, build)] = (code, wrote)
            total += 1
            if code and (key, build) not in EXPECTED_FAULTS:
                unexpected.append((key, build, code))
    ini.unlink(missing_ok=True)
    out.unlink(missing_ok=True)

    if options.tsv:
        rows = ["# key\tbuild\texit\tbytes", "# generated by tools/single_key_matrix.py"]
        for build in builds:
            for key in table:
                code, wrote = results[(key, build)]
                rows.append(f"{key}\t{build}\t{code:#010x}\t{wrote}")
        options.tsv.parent.mkdir(parents=True, exist_ok=True)
        options.tsv.write_text("\n".join(rows) + "\n", encoding="utf-8")

    if not options.quiet:
        header = "key".ljust(34) + "".join(f"b{build}".rjust(5) for build in builds)
        print(header)
        print("-" * len(header))
        for key in table:
            line = key.ljust(34)
            for build in builds:
                line += cell_text(results[(key, build)][0]).rjust(5)
            print(line)

    faults = [(key, build, code) for (key, build), (code, _) in results.items() if code]
    print()
    print(f"single-key matrix: {len(builds)} build(s) x {len(table)} key(s) = {total} cell(s)")
    for key, build, code in sorted(faults):
        note = "expected, preserved original fault" if (key, build) in EXPECTED_FAULTS else "UNEXPECTED"
        print(f"  FAULTED {key} on build {build} ({VERSIONS[build]}): {exception_of(code) or code} [{note}]")
    for key, build, code in unexpected:
        print(f"  FAIL {key} on build {build}: exit {code:#010x}")
    if not unexpected:
        print(f"  every other cell exited 0 ({total - len(faults)} of {total})")
    return 1 if unexpected else 0


if __name__ == "__main__":
    sys.exit(main())
