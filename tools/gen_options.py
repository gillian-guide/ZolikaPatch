#!/usr/bin/env python3
"""Generate source/options.inc from the behaviour inventory.

The catalogue is recovered data: every `[Options]` key, its shipped value, the
default the arm passes when the key is absent, the builds the key applies to and
the module that owns it. The source of truth is the inventory produced from the
old tree and cross-checked against the shipped ZolikaPatch.ini; this script only
serialises it, so the table is never hand-edited.

    python tools/gen_options.py [--check]

`--check` regenerates into memory and fails if the committed file differs.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT.parent / ".agents" / "rewrite" / "03-readable-inventory.md"
OUTPUT = ROOT / "source" / "options.inc"

# Compact build ids, exactly as the original's switch names them.
BUILDS = {
    "1.0.0.0": 1000,
    "1.0.0.4": 1004,
    "1.0.4.0": 1040,
    "1.0.6.0": 1060,
    "1.0.6.1": 1061,
    "1.0.7.0": 1070,
    "1.0.8.0": 1080,
    "1.1.0.0": 1100,
    "1.1.1.0": 1110,
    "1.1.2.0": 1120,
    "1.1.3.0": 1130,
    "1.2.0.43": 12043,
}

ORDINAL = {
    1000: 1, 1004: 6, 1040: 5, 1060: 7, 1061: 15, 1070: 8,
    1080: 9, 1100: 10, 1110: 11, 1120: 12, 1130: 13, 12043: 18,
}

SHORTHANDS = {
    "ALL": list(BUILDS),
    "G10": ["1.0.0.4", "1.0.6.0", "1.0.6.1", "1.0.7.0", "1.0.8.0",
            "1.1.0.0", "1.1.1.0", "1.1.2.0", "1.1.3.0", "1.2.0.43"],
    "G8VS": ["1.0.0.4", "1.0.6.0", "1.0.6.1", "1.0.7.0", "1.1.0.0",
             "1.1.1.0", "1.1.2.0", "1.2.0.43"],
    "S10": ["1.0.0.0", "1.0.4.0", "1.0.0.4", "1.0.6.0", "1.0.7.0",
            "1.0.6.1", "1.1.0.0", "1.1.1.0", "1.1.2.0", "1.2.0.43"],
}

ROW = re.compile(r"^\|\s*`([A-Za-z0-9_]+)`\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|")
MODULE = re.compile(r"^###\s+2\.\d+\s+`zp\.([a-z]+)`")


def mask_for(text):
    text = text.strip()
    if text in SHORTHANDS:
        builds = SHORTHANDS[text]
    else:
        tokens = [part.strip() for part in re.split(r"[,/]", text)]
        # A cell that mixes prose with build ids used to be parsed by dropping the
        # prose silently, which produced a mask that looked plausible and was wrong:
        # DualVehicleHeadlights came out as 1.0.4.0-only when the original gates it
        # on every build. Refusing is the only safe failure mode for a generated
        # table - the cell must say ALL, a shorthand, or nothing but build ids.
        builds = [part for part in tokens if part in BUILDS or part.isdigit()]
        unparseable = [part for part in tokens if part and part not in builds]
        if unparseable:
            raise SystemExit(f"build cell is not machine-readable: {text!r} "
                             f"(unparseable: {unparseable})")
    mask = 0
    for name in builds:
        compact = BUILDS[name] if name in BUILDS else int(name)
        mask |= 1 << ORDINAL[compact]
    return mask, builds


def parse():
    rows = []
    module = None
    for line in INVENTORY.read_text(encoding="utf-8", errors="replace").splitlines():
        header = MODULE.match(line)
        if header:
            module = header.group(1)
            continue
        match = ROW.match(line)
        if not match or module is None:
            continue
        key, shipped, absent, builds = match.groups()
        shipped = shipped.replace("*", "").strip()
        absent = absent.replace("*", "").strip()

        # The one string-valued key: the loader only pre-reads it (the setter is
        # called when it is present), so it has no numeric default at all.
        if key == "OverrideGTADatPathTo":
            mask, names = mask_for(builds)
            rows.append((key, -1, -1, mask, module, names, "string"))
            continue
        # The undocumented alias: absent from the shipped INI, numeric default 0.
        if key == "Patch7RemoveModChecks":
            mask, names = mask_for(builds)
            rows.append((key, -1, int(absent), mask, module, names, "alias"))
            continue
        if not shipped.isdigit() or not absent.isdigit():
            continue
        mask, names = mask_for(builds) if builds.strip() in SHORTHANDS else mask_for(builds.replace("**", " "))
        rows.append((key, int(shipped), int(absent), mask, module, names, "numeric"))
    return rows


def render(rows):
    lines = [
        "// Generated by tools/gen_options.py -- do not edit.",
        "//",
        "// Every [Options] key: the value the shipped INI carries, the default the",
        "// original passes when the key is absent, the builds the key applies to (a",
        "// build mask indexed by the original's build id) and the module that owns",
        "// it. Recovered data; the inventory it is generated from is checked against",
        "// game_refs/ZolikaPatch.ini.",
        "",
        "ZP_OPTION(RemoveUselessChecks, 0, 0, mask_remove_useless_checks, misc)",
    ]
    # The first row above is a placeholder for the reader's eye; every real row
    # follows in inventory order.
    lines = lines[:-1]
    for key, shipped, absent, mask, module, names, kind in rows:
        lines.append(f"ZP_OPTION({key}, {shipped}, {absent}, 0x{mask:08X}u, {module}, {kind})")
    return "\n".join(lines) + "\n"


def main():
    if not INVENTORY.exists():
        # The inventory is a research note kept outside this repository. Without it
        # there is nothing to compare the catalogue against, which is not drift.
        print(f"skip: {INVENTORY} is absent, so the catalogue has nothing to be checked against")
        return
    rows = parse()
    if len(rows) < 99:
        raise SystemExit(f"only {len(rows)} option rows parsed -- the inventory layout changed")
    text = render(rows)
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("source/options.inc is out of date; run tools/gen_options.py")
        print(f"options.inc up to date ({len(rows)} rows)")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
