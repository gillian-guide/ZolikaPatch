#!/usr/bin/env python3
"""Classify every hex literal in readable's hand-written sources.

The project rule is: no bare `0x...` in code without an intuitive name or an
exact adjacent reason. This tool makes that rule checkable instead of a claim.

Classes (one per literal occurrence in code; comments and strings are excluded):

  named       the literal is a named declaration's initialiser: a constexpr /
              const / enum member / macro / static_assert expectation, or an
              element of a named brace-initialised array or struct table. The
              declaration's name is the intuitive name. A view struct's
              `std::byte pad_NNNN[...]` extent counts too: the pad's name and
              the next field's comment state the recovered layout at the
              declaration.
  documented  the literal carries an adjacent exact reason: its own trailing
              comment or the comment line directly above starts with
              `why:`, `opaque:`, `orig:` or `provenance:`.
  asm         the literal is an operand of an `__asm` block whose enclosing body
              carries an `@exact` marker. It is a recovered instruction operand,
              not a magic number: tools/verify_bodies.py proves the whole byte
              sequence against the original ASI, so renaming an immediate would
              obscure the 1:1 correspondence with the disassembly.
  unclassified  none of the above: the check fails.

Usage:
    python tools/magic_numbers.py            # per-file summary
    python tools/magic_numbers.py --list     # every unclassified occurrence
    python tools/magic_numbers.py --check    # exit 1 if anything is unclassified
    python tools/magic_numbers.py --tsv PATH # full inventory for the report
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Generated tables are data, not decisions: their literals are recovered rows and
# are regenerated by tools/, never renamed (research 07).
GENERATED = {
    "src/catalogue_data.cpp",
    "src/ooc_payload.h",
    "src/useless_checks_data.inc",
}

HEX = re.compile(r"0x[0-9A-Fa-f]+")
IDENT_HEX = re.compile(r"\w*0x[0-9A-Fa-f]+\w*")
NAMED_INIT = re.compile(r"\b(\w+)\s*(?:\[[^\]]*\])?\s*=\s*\{\s*$")
NAMED_DECL = re.compile(
    r"^\s*(?:(?:static|inline|constexpr|const|constinit|volatile|mutable)\s+|"
    r"alignas\s*\([^)]*\)\s*)*"
    r"[\w:<>,]+(?:[\s*&]+[\w:<>,]+)*[\s*&]+(?P<name>\w+)\s*"
    r"(?:\[[^\]]*\])?\s*(?:=|\{)\s*")
ASSERT = re.compile(r"^\s*static_assert\s*\(")
# A view struct's pad: `std::byte pad_0030[0xE18 - 0x30];` states the recovered
# offset extent at the declaration itself (the `pad_` name says where it ends),
# which is the rule's goal; the field comment names what starts there.
PAD_DECL = re.compile(r"\bpad_[0-9A-Fa-f]+\s*\[")
ENUM_START = re.compile(r"^\s*enum\s+(?:class\s+|struct\s+)?\w+")
ENUM_OPEN = re.compile(r"^\s*\{")
MACRO = re.compile(r"^\s*#define\s+\w+\s+")
MARKER = re.compile(r"^\s*(why|opaque|orig|provenance):", re.I)


def strip_strings(code: str) -> str:
    """Drop string and character literals so their bytes are not counted."""
    out = []
    quote = None
    escaped = False
    for char in code:
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            out.append(" ")
            continue
        if char in "\"'":
            quote = char
            out.append(" ")
            continue
        out.append(char)
    return "".join(out)


def split_comment(line: str):
    code, sep, comment = line.partition("//")
    return code, (comment if sep else "")


def iter_sources(include_tests: bool = True):
    paths = []
    for pattern in ("src/**/*.cpp", "src/**/*.h", "src/**/*.inc", "source/*.ixx",
                    "source/*.cpp",
                    "tests/*.cpp", "tests/*.h"):
        paths.extend(ROOT.glob(pattern))
    for path in sorted(set(paths)):
        rel = path.relative_to(ROOT).as_posix()
        if rel in GENERATED:
            continue
        if not include_tests and rel.startswith("tests/"):
            continue
        yield path, rel


def doc_above(lines, index: int) -> str:
    """The comment block above the function containing line `index`."""
    probe = index - 1
    # Walk to the function's definition line (column 0, has a parameter list).
    while probe >= 0:
        line = lines[probe]
        if line[:1] not in (" ", "\t") and "(" in line and not line.lstrip().startswith("//"):
            break
        probe -= 1
    collected = []
    probe -= 1
    while probe >= 0:
        stripped = lines[probe].strip()
        if stripped.startswith("//"):
            collected.append(stripped[2:].strip())
        elif stripped == "":
            if collected:
                break
        elif re.fullmatch(r"(namespace\s*\{?|\{|\}|extern \"C\")", stripped):
            pass
        else:
            break
        probe -= 1
    return " ".join(reversed(collected))


def documented(lines, index: int, comment: str) -> bool:
    """An adjacent exact reason: this line's trailing comment or the block above."""
    if comment and MARKER.match(comment):
        return True
    probe = index - 1
    while probe >= 0:
        stripped = lines[probe].strip()
        if stripped.startswith("//"):
            if MARKER.match(stripped[2:].strip()):
                return True
        elif stripped == "" or stripped.startswith("*"):
            return False
        else:
            return False
        probe -= 1
    return False


def scan(path: pathlib.Path, rel: str):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    findings = []
    brace = 0
    named_inside = None
    enum_inside = None
    asm_inside = None
    asm_exact = False
    function_exact = False
    enum_pending = False
    assert_inside = False
    comment_above = ""

    for number, raw in enumerate(lines, 1):
        code, comment = split_comment(raw)
        code = strip_strings(code)

        if "@exact" in raw:
            function_exact = True

        # A block opened by a previous line is closed once this line starts at a
        # shallower depth than its contents.
        if named_inside is not None and brace < named_inside:
            named_inside = None
        if enum_inside is not None and brace < enum_inside:
            enum_inside = None
        if asm_inside is not None and brace < asm_inside:
            asm_inside = None

        if ASSERT.match(code):
            assert_inside = True
        opens = code.count("{")
        closes = code.count("}")
        net = opens - closes
        if ENUM_START.match(code):
            enum_pending = True
        if enum_pending and opens:
            enum_inside = brace + net if net > 0 else brace + 1
            enum_pending = False
        if (NAMED_INIT.search(code) or NAMED_DECL.match(code)) and "{" in code and net > 0:
            named_inside = brace + net
        if "__asm" in code and opens:
            asm_inside = brace + net if net > 0 else brace + 1
            # A transcribed body's asm literals are recovered instruction
            # operands: the disassembly is the source, and renaming an immediate
            # would obscure the 1:1 correspondence. tools/verify_bodies.py
            # proves every registered @exact body; the helper bodies are called
            # from them and their leading comments name the original function.
            asm_exact = True

        literals = list(HEX.finditer(code))
        for match in literals:
            # `spawns_case_0x24` / `abi_spawns_case_0x24` are identifiers, not
            # literals: the digits are part of the name.
            if match.start() > 0 and (code[match.start() - 1].isalnum()
                                      or code[match.start() - 1] == "_"):
                continue
            prefix = code[: match.start()]
            named = False
            if named_inside is not None:
                named = brace >= named_inside or (brace + net >= named_inside)
            if enum_inside is not None and (brace >= enum_inside or brace + net >= enum_inside):
                named = True
            if NAMED_DECL.match(code):
                named = True
            if ASSERT.match(code) or assert_inside:
                named = True
            if PAD_DECL.search(code):
                named = True
            if MACRO.match(code):
                named = True
            if named:
                kind = "named"
            elif documented(lines, number - 1, comment):
                kind = "documented"
            elif asm_inside is not None:
                kind = "asm"
            else:
                kind = "unclassified"
            findings.append({
                "path": rel,
                "line": number,
                "value": match.group(0),
                "column": match.start() + 1,
                "kind": kind,
                "text": raw.strip(),
            })

        brace += net
        if assert_inside and ");" in code:
            assert_inside = False
        comment_above = comment.strip() if comment else ""
    return findings


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail on unclassified literals")
    parser.add_argument("--list", action="store_true", help="list unclassified occurrences")
    parser.add_argument("--tsv", metavar="PATH", help="write the full inventory")
    parser.add_argument("--no-tests", action="store_true")
    args = parser.parse_args(argv)

    all_findings = []
    for path, rel in iter_sources(include_tests=not args.no_tests):
        all_findings.extend(scan(path, rel))

    by_kind: dict[str, int] = {}
    by_file: dict[str, dict[str, int]] = {}
    for finding in all_findings:
        by_kind[finding["kind"]] = by_kind.get(finding["kind"], 0) + 1
        row = by_file.setdefault(finding["path"], {})
        row[finding["kind"]] = row.get(finding["kind"], 0) + 1

    for rel, kinds in sorted(by_file.items()):
        summary = ", ".join(f"{kind} {count}" for kind, count in sorted(kinds.items()))
        print(f"{rel}: {summary}")
    print("\ntotal:", ", ".join(f"{kind} {count}" for kind, count in sorted(by_kind.items())))

    if args.tsv:
        with open(args.tsv, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("path\tline\tcolumn\tvalue\tkind\ttext\n")
            for finding in all_findings:
                handle.write(f"{finding['path']}\t{finding['line']}\t{finding['column']}\t"
                             f"{finding['value']}\t{finding['kind']}\t{finding['text']}\n")

    unclassified = [f for f in all_findings if f["kind"] == "unclassified"]
    if args.list:
        for finding in unclassified:
            print(f"  {finding['path']}:{finding['line']}:{finding['column']} "
                  f"{finding['value']}  {finding['text']}")
    print(f"\nunclassified: {len(unclassified)}")
    if args.check and unclassified:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
